type diagramState struct {
	mu            sync.Mutex
	source        string
	dark, loading bool
	image         *ui.Bitmap
	err           error
	showSource    bool
	zoom          float32
}

func nativeDiagram(c *ui.Context, b *markdown.CodeBlockView) {
	box := ui.Column(c).MinWidth(0).Gap(8).Padding(10).Background(c.Theme().Surface).Border(1, c.Theme().Border).Radius(8)
	state := *ui.Local(box, "diagram", func() *diagramState { return &diagramState{zoom: 1} })
	src, dark := b.Code(), c.Theme().Dark
	state.mu.Lock()
	if !b.Open && (state.source != src || state.dark != dark) {
		state.source, state.dark, state.loading = src, dark, true
		services := c.Services()
		go func() {
			img, err := renderDiagram(src, dark)
			state.mu.Lock()
			if state.source == src && state.dark == dark {
				state.image, state.err, state.loading = img, err, false
			}
			state.mu.Unlock()
			services.Invalidate()
		}()
	}
	img, err, loading := state.image, state.err, state.loading
	state.mu.Unlock()
	box.Children(func() {
		ui.Row(c).Gap(6).Children(func() {
			ui.Text(c, "Mermaid").FontSize(12).TextColor(c.Theme().TextMuted)
			ui.Spacer(c)
			tabButton(c, "图表", !state.showSource).OnClick(func() { state.showSource = false })
			tabButton(c, "源码", state.showSource).OnClick(func() { state.showSource = true })
			flatButton(c, "copy", "复制图表源码").OnClick(func() { c.WriteClipboard(src) })
		})
		if state.showSource {
			b.Body(c)
			return
		}
		if b.Open || loading {
			ui.Text(c, "正在生成图表…").FontSize(12).TextColor(c.Theme().TextMuted)
		}
		if err != nil {
			ui.Text(c, "图表无法呈现："+err.Error()).FontSize(12).TextColor(c.Theme().Warning)
			b.Body(c)
			return
		}
		if img != nil {
			ui.Row(c).Gap(6).Children(func() {
				ui.Spacer(c)
				flatButton(c, "", "−").Label("缩小图表").OnClick(func() { state.zoom = max(.5, state.zoom-.25) })
				flatButton(c, "", fmt.Sprintf("%.0f%%", state.zoom*100)).Label("重置图表缩放").OnClick(func() { state.zoom = 1 })
				flatButton(c, "", "+").Label("放大图表").OnClick(func() { state.zoom = min(3, state.zoom+.25) })
			})
			ui.Scroll(c).MaxHeight(600).Children(func() {
				ui.ScrollHorizontal(c).Children(func() {
					w, h := img.Size()
					ui.Image(c, img).Width(float32(w) * state.zoom / 2).Height(float32(h) * state.zoom / 2).Label("Mermaid 图表")
				})
			})
		}
	})
}
func renderDiagram(source string, dark bool) (*ui.Bitmap, error) {
	if len(source) > 16000 || strings.Count(source, "\n") > 160 {
		return nil, errors.New("图表较大，请拆分成多个图表")
	}
	theme := mermaid.Default
	if dark {
		theme = mermaid.Dark
	}
	data, err := mermaid.Render(source, mermaid.WithTheme(theme))
	if err != nil {
		return nil, err
	}
	data, err = diagramTextPaths(data)
	if err != nil {
		return nil, err
	}
	var root svgTextNode
	if err = xml.Unmarshal(data, &root); err != nil {
		return nil, err
	}
	var x, y, w, h float64
	fmt.Sscanf(root.attr("viewBox"), "%f %f %f %f", &x, &y, &w, &h)
	scale := 2.0
	if w <= 0 || h <= 0 {
		return nil, errors.New("图表尺寸无效")
	}
	if w*scale > 3200 {
		scale = 3200 / w
	}
	if h*scale > 3200 {
		scale = 3200 / h
	}
	data, err = raster.RasterizeSVG(data, scale)
	if err != nil {
		return nil, err
	}
	return ui.DecodeBitmap(data)
}

// The native SVG renderer intentionally leaves out text. Convert only the
// labels generated by the Go renderer to font outlines before rasterizing.
// No document-supplied font paths, URLs or scripts are loaded.
type svgTextNode struct {
	XMLName  xml.Name
	Attrs    []xml.Attr    `xml:",any,attr"`
	Text     string        `xml:",chardata"`
	Children []svgTextNode `xml:",any"`
}

func (n svgTextNode) attr(key string) string {
	for _, a := range n.Attrs {
		if a.Name.Local == key {
			return a.Value
		}
	}
	return ""
}
func svgNumber(raw string, fallback float64) float64 {
	if v, err := strconv.ParseFloat(raw, 64); err == nil {
		return v
	}
	return fallback
}

var diagramFonts struct {
	sync.Once
	latin, cjk *sfnt.Font
}

func loadDiagramFonts() {
	diagramFonts.Do(func() {
		diagramFonts.latin, _ = sfnt.Parse(goregular.TTF)
		for _, path := range []string{"/System/Library/Fonts/STHeiti Light.ttc", "/usr/share/fonts/truetype/noto/NotoSansCJK-Regular.ttc"} {
			data, err := os.ReadFile(path)
			if err != nil {
				continue
			}
			collection, err := sfnt.ParseCollection(data)
			if err == nil {
				diagramFonts.cjk, _ = collection.Font(0)
				break
			}
		}
	})
}
func diagramTextPaths(data []byte) ([]byte, error) {
	loadDiagramFonts()
	var root svgTextNode
	if err := xml.Unmarshal(data, &root); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	var draw func(svgTextNode, float64, string, string)
	draw = func(n svgTextNode, size float64, fill, anchor string) {
		size = svgNumber(n.attr("font-size"), size)
		if n.attr("fill") != "" {
			fill = n.attr("fill")
		}
		if n.attr("text-anchor") != "" {
			anchor = n.attr("text-anchor")
		}
		if n.XMLName.Local == "text" {
			out.WriteString("<g")
			if tr := n.attr("transform"); tr != "" {
				out.WriteString(" transform=\"")
				xml.EscapeText(&out, []byte(tr))
				out.WriteByte('"')
			}
			out.WriteByte('>')
			x, y := svgNumber(n.attr("x"), 0), svgNumber(n.attr("y"), 0)+svgNumber(n.attr("dy"), 0)
			if strings.TrimSpace(n.Text) != "" {
				writeDiagramGlyphs(&out, n.Text, x, y, size, fill, anchor)
			}
			for _, span := range n.Children {
				x = svgNumber(span.attr("x"), x)
				y = svgNumber(span.attr("y"), y) + svgNumber(span.attr("dy"), 0)
				writeDiagramGlyphs(&out, span.Text, x, y, svgNumber(span.attr("font-size"), size), fill, anchor)
			}
			out.WriteString("</g>")
			return
		}
		out.WriteByte('<')
		out.WriteString(n.XMLName.Local)
		for _, a := range n.Attrs {
			out.WriteByte(' ')
			out.WriteString(a.Name.Local)
			out.WriteString("=\"")
			xml.EscapeText(&out, []byte(a.Value))
			out.WriteByte('"')
		}
		out.WriteByte('>')
		xml.EscapeText(&out, []byte(n.Text))
		for _, child := range n.Children {
			draw(child, size, fill, anchor)
		}
		out.WriteString("</")
		out.WriteString(n.XMLName.Local)
		out.WriteByte('>')
	}
	draw(root, 14, "#222222", "start")
	return out.Bytes(), nil
}
func writeDiagramGlyphs(out *bytes.Buffer, text string, x, y, size float64, fill, anchor string) {
	type glyph struct {
		f       *sfnt.Font
		id      sfnt.GlyphIndex
		advance float64
	}
	var glyphs []glyph
	var buf sfnt.Buffer
	ppem := fixed.Int26_6(size * 64)
	width := 0.0
	for _, r := range text {
		f := diagramFonts.latin
		id, _ := f.GlyphIndex(&buf, r)
		if id == 0 && diagramFonts.cjk != nil {
			f = diagramFonts.cjk
			id, _ = f.GlyphIndex(&buf, r)
		}
		advance, _ := f.GlyphAdvance(&buf, id, ppem, font.HintingNone)
		a := float64(advance) / 64
		glyphs = append(glyphs, glyph{f, id, a})
		width += a
	}
	if anchor == "middle" {
		x -= width / 2
	} else if anchor == "end" {
		x -= width
	}
	out.WriteString("<path fill=\"")
	xml.EscapeText(out, []byte(fill))
	out.WriteString("\" d=\"")
	for _, g := range glyphs {
		segs, err := g.f.LoadGlyph(&buf, g.id, ppem, nil)
		if err == nil {
			for _, s := range segs {
				switch s.Op {
				case sfnt.SegmentOpMoveTo:
					fmt.Fprintf(out, "M%.3f %.3f", x+float64(s.Args[0].X)/64, y+float64(s.Args[0].Y)/64)
				case sfnt.SegmentOpLineTo:
					fmt.Fprintf(out, "L%.3f %.3f", x+float64(s.Args[0].X)/64, y+float64(s.Args[0].Y)/64)
				case sfnt.SegmentOpQuadTo:
					fmt.Fprintf(out, "Q%.3f %.3f %.3f %.3f", x+float64(s.Args[0].X)/64, y+float64(s.Args[0].Y)/64, x+float64(s.Args[1].X)/64, y+float64(s.Args[1].Y)/64)
				case sfnt.SegmentOpCubeTo:
					fmt.Fprintf(out, "C%.3f %.3f %.3f %.3f %.3f %.3f", x+float64(s.Args[0].X)/64, y+float64(s.Args[0].Y)/64, x+float64(s.Args[1].X)/64, y+float64(s.Args[1].Y)/64, x+float64(s.Args[2].X)/64, y+float64(s.Args[2].Y)/64)
				}
			}
		}
		x += g.advance
	}
	out.WriteString("\"/>")
}
